#!/usr/bin/env bash

set -Eeuo pipefail

log_info() {
    printf '[isoforms-install] %s\n' "$*"
}

die() {
    printf '[isoforms-install] ERROR: %s\n' "$*" >&2
    exit 1
}

usage() {
    cat <<'EOF'
Usage:
  install.sh --assembly GRCh37|GRCh38 --db-root DIR \
    --module-db-root DIR --conda-env NAME [--threads N]

This module uses the RSEM isoform results generated by the core pipeline. It
does not download an additional reference or install additional software.
EOF
}

ASSEMBLY=""
DB_ROOT=""
MODULE_DB_ROOT=""
CONDA_ENV=""
THREADS=8

while (( $# > 0 )); do
    case "$1" in
        --assembly)
            [[ $# -ge 2 ]] || die "--assembly requires a value"
            ASSEMBLY="$2"
            shift 2
            ;;
        --db-root)
            [[ $# -ge 2 ]] || die "--db-root requires a value"
            DB_ROOT="$2"
            shift 2
            ;;
        --module-db-root)
            [[ $# -ge 2 ]] || die "--module-db-root requires a value"
            MODULE_DB_ROOT="$2"
            shift 2
            ;;
        --conda-env)
            [[ $# -ge 2 ]] || die "--conda-env requires a value"
            CONDA_ENV="$2"
            shift 2
            ;;
        --threads)
            [[ $# -ge 2 ]] || die "--threads requires a value"
            THREADS="$2"
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            die "Unknown argument: $1"
            ;;
    esac
done

case "${ASSEMBLY,,}" in
    grch38|hg38)
        ASSEMBLY="GRCh38"
        ;;
    grch37|hg19)
        ASSEMBLY="GRCh37"
        ;;
    *)
        die "--assembly must be GRCh37, hg19, GRCh38, or hg38"
        ;;
esac

[[ -d "$DB_ROOT" ]] || die "--db-root was not found: $DB_ROOT"
[[ -n "$MODULE_DB_ROOT" ]] || die "--module-db-root is required"
[[ -n "$CONDA_ENV" ]] || die "--conda-env is required"
[[ "$THREADS" =~ ^[1-9][0-9]*$ ]] ||
    die "--threads must be a positive integer"
command -v python3 >/dev/null 2>&1 ||
    die "python3 is required by the isoforms aggregator"

CONFIG_DIR="${MODULE_DB_ROOT}/config"
mkdir -p "$CONFIG_DIR"

cat > "${CONFIG_DIR}/${ASSEMBLY}.config" <<EOF
ISOFORMS_ASSEMBLY='$ASSEMBLY'
ISOFORMS_CONDA_ENV='$CONDA_ENV'
EOF

log_info "Installed $ASSEMBLY configuration in $CONFIG_DIR"
