#!/usr/bin/env bash

set -Eeuo pipefail

die() {
    printf '[fusion] ERROR: %s\n' "$*" >&2
    exit 1
}

usage() {
    cat <<'EOF'
Usage:
  run_module.sh --sample ID --layout single|paired --read1 FILE \
    [--read2 FILE] --output-dir DIR --assembly GRCh37|GRCh38 \
    --db-root DIR [--threads N]

This is the uniform NF-RNAseq optional-module entry point. It loads the
assembly-specific fusion configuration generated by install_pipe.sh and calls
run_fusion.sh.
EOF
}

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"

SAMPLE=""
READ_LAYOUT=""
READ1=""
READ2=""
OUTPUT_DIR=""
ASSEMBLY=""
DB_ROOT=""
THREADS=8

while (( $# > 0 )); do
    case "$1" in
        --sample)
            [[ $# -ge 2 ]] || die "--sample requires a value"
            SAMPLE="$2"
            shift 2
            ;;
        --layout)
            [[ $# -ge 2 ]] || die "--layout requires a value"
            READ_LAYOUT="${2,,}"
            shift 2
            ;;
        --read1)
            [[ $# -ge 2 ]] || die "--read1 requires a value"
            READ1="$2"
            shift 2
            ;;
        --read2)
            [[ $# -ge 2 ]] || die "--read2 requires a value"
            READ2="$2"
            shift 2
            ;;
        --output-dir)
            [[ $# -ge 2 ]] || die "--output-dir requires a value"
            OUTPUT_DIR="$2"
            shift 2
            ;;
        --assembly)
            [[ $# -ge 2 ]] || die "--assembly requires a value"
            ASSEMBLY="$2"
            shift 2
            ;;
        --db-root)
            [[ $# -ge 2 ]] || die "--db-root requires a value"
            DB_ROOT="$2"
            shift 2
            ;;
        --threads)
            [[ $# -ge 2 ]] || die "--threads requires a value"
            THREADS="$2"
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            die "Unknown argument: $1"
            ;;
    esac
done

[[ -n "$SAMPLE" ]] || die "--sample is required"
[[ "$READ_LAYOUT" == "single" || "$READ_LAYOUT" == "paired" ]] ||
    die "--layout must be single or paired"
[[ -s "$READ1" ]] || die "--read1 is missing or empty: $READ1"
if [[ "$READ_LAYOUT" == "paired" ]]; then
    [[ -s "$READ2" ]] || die "--read2 is missing or empty: $READ2"
fi
[[ -n "$OUTPUT_DIR" ]] || die "--output-dir is required"
[[ "$ASSEMBLY" == "GRCh37" || "$ASSEMBLY" == "GRCh38" ]] ||
    die "--assembly must resolve to GRCh37 or GRCh38"
[[ -d "$DB_ROOT" ]] || die "--db-root was not found: $DB_ROOT"
[[ "$THREADS" =~ ^[1-9][0-9]*$ ]] || die "--threads must be a positive integer"

MODULE_CONFIG="${DB_ROOT}/shared/fusion_module/config/${ASSEMBLY}.config"
[[ -s "$MODULE_CONFIG" ]] ||
    die "Fusion module is not installed for $ASSEMBLY: $MODULE_CONFIG"

# shellcheck disable=SC1090
source "$MODULE_CONFIG"

REQUIRED_CONFIG_VARIABLES=(
    FUSION_ASSEMBLY
    FUSION_CTAT_GENOME_LIB
    FUSION_ARRIBA_BLACKLIST
    FUSION_ARRIBA_KNOWN_FUSIONS
    FUSION_ARRIBA_PROTEIN_DOMAINS
    FUSION_STAR_FUSION_EXECUTABLE
    FUSION_CONDA_ENV
)

for variable_name in "${REQUIRED_CONFIG_VARIABLES[@]}"; do
    [[ -n "${!variable_name:-}" ]] ||
        die "Fusion configuration variable is missing: $variable_name"
done

[[ "$FUSION_ASSEMBLY" == "$ASSEMBLY" ]] ||
    die "Fusion configuration is for $FUSION_ASSEMBLY, not $ASSEMBLY"
[[ "${CONDA_DEFAULT_ENV:-}" == "$FUSION_CONDA_ENV" ]] ||
    die "Conda environment '$FUSION_CONDA_ENV' is not active"
[[ -x "${SCRIPT_DIR}/run_fusion.sh" ]] ||
    die "Fusion runtime is missing: ${SCRIPT_DIR}/run_fusion.sh"

runtime_arguments=(
    --sample "$SAMPLE"
    --layout "$READ_LAYOUT"
    --read1 "$READ1"
    --output-dir "$OUTPUT_DIR"
    --ctat-genome-lib "$FUSION_CTAT_GENOME_LIB"
    --arriba-blacklist "$FUSION_ARRIBA_BLACKLIST"
    --arriba-known-fusions "$FUSION_ARRIBA_KNOWN_FUSIONS"
    --arriba-protein-domains "$FUSION_ARRIBA_PROTEIN_DOMAINS"
    --star-fusion-executable "$FUSION_STAR_FUSION_EXECUTABLE"
    --threads "$THREADS"
)

if [[ "$READ_LAYOUT" == "paired" ]]; then
    runtime_arguments+=(--read2 "$READ2")
fi

exec "${SCRIPT_DIR}/run_fusion.sh" "${runtime_arguments[@]}"
